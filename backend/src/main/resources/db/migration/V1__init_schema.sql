-- Flyway Migration V1: Initial Schema

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE habits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    frequency_type VARCHAR(50) NOT NULL, -- e.g., 'DAILY', 'WEEKDAYS', 'SPECIFIC_DAYS'
    days_of_week VARCHAR(100),          -- comma-separated: 'MON,TUE,WED' or json string
    target_time VARCHAR(20),            -- optional target time e.g. '08:00'
    color VARCHAR(30) DEFAULT '#10B981', -- hex color code
    archived BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_habits_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_habits_user_id ON habits(user_id);

CREATE TABLE habit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id BIGINT NOT NULL,
    log_date DATE NOT NULL,
    completed BOOLEAN DEFAULT FALSE NOT NULL,
    note TEXT,
    CONSTRAINT fk_habit_logs_habit FOREIGN KEY (habit_id) REFERENCES habits(id) ON DELETE CASCADE,
    CONSTRAINT uk_habit_logs_habit_date UNIQUE (habit_id, log_date)
);

CREATE INDEX idx_habit_logs_habit_date ON habit_logs(habit_id, log_date);
